# Keyed by *filename*; value is the asyncio.Task running run_td_cli for that file.
# Serves two purposes for the short-cost synchronous path:
#   1. Deduplication key — detect whether this exact file is already being generated.
#   2. Awaitable handle — late-arriving requests for the same file can join (await)
#      the in-flight task instead of spawning a second subprocess.
# Note: source-level serialization (preventing two different files of the same source
# from running concurrently) is handled separately via _source_locks / _get_source_lock.
_active_processes: dict[str, "asyncio.Task[int]"] = {}

# Keyed by source name (action[0], e.g. "otbr-cli", "mdns", "otbr-restapi").
# Each lock serializes all td_cli subprocesses for that source so that only one
# runs at a time, preventing hardware/socket conflicts in the underlying CLI layer.
# In a long-lived server with many unique source keys this dict could grow
# unbounded. If that becomes a concern, add periodic cleanup (e.g. evict locks
# that are not locked and have not been used recently).
_source_locks: dict[str, asyncio.Lock] = {}


def _get_source_lock(source: str) -> asyncio.Lock:
    """Return the asyncio.Lock for *source*, creating it lazily if absent."""
    if source not in _source_locks:
        _source_locks[source] = asyncio.Lock()
    return _source_locks[source]


# async job tracking
_LONG_COST_THRESHOLD_S = 300  # actions with cost > this get 202 + polling

# Phase 1 contract: explicit job status model used by polling/cancel APIs.
JOB_STATUS_RUNNING = "running"
JOB_STATUS_CANCELLING = "cancelling"
JOB_STATUS_CANCELLED = "cancelled"
JOB_STATUS_DONE = "done"
JOB_STATUS_ERROR = "error"

_JOB_TERMINAL_STATUSES: set[str] = {
    JOB_STATUS_CANCELLED,
    JOB_STATUS_DONE,
    JOB_STATUS_ERROR,
}

_JOB_CANCELLABLE_STATUSES: set[str] = {JOB_STATUS_RUNNING}


@dataclasses.dataclass
class JobStatus:
    job_id: str
    filename: str
    # "running" | "cancelling" | "cancelled" | "done" | "error"
    status: str
    detail: str = ""
    created_at: float = dataclasses.field(default_factory=time.time)


@dataclasses.dataclass
class JobRuntime:
    """In-memory runtime handles for a long-cost job."""

    job_id: str
    filename: str
    source: str
    task: "asyncio.Task[None]"
    process: "asyncio.subprocess.Process | None" = None


def _is_terminal_job_status(status: str) -> bool:
    """Return True when *status* is a terminal job state."""
    return status in _JOB_TERMINAL_STATUSES


def _is_cancellable_job_status(status: str) -> bool:
    """Return True when *status* is currently cancellable."""
    return status in _JOB_CANCELLABLE_STATUSES


def _build_job_poll_body(job: JobStatus) -> dict[str, object]:
    """Build JSON payload for GET /api/job/{job_id} based on status."""
    if job.status == JOB_STATUS_RUNNING:
        return {"status": JOB_STATUS_RUNNING}
    if job.status == JOB_STATUS_CANCELLING:
        return {"status": JOB_STATUS_CANCELLING}
    if job.status == JOB_STATUS_CANCELLED:
        return {"status": JOB_STATUS_CANCELLED, "detail": job.detail}
    if job.status == JOB_STATUS_DONE:
        return {"status": JOB_STATUS_DONE, "filename": job.filename}
    # Unknown statuses are surfaced as error payloads to keep polling robust.
    if job.status != JOB_STATUS_ERROR:
        return {
            "status": JOB_STATUS_ERROR,
            "detail": f"Unknown job status: {job.status}",
        }
    return {"status": JOB_STATUS_ERROR, "detail": job.detail}


def _to_epoch_ms(ts: float) -> int:
    """Convert a POSIX timestamp in seconds to integer epoch milliseconds."""
    return int(ts * 1000)


def _build_checkpoint_poll_metadata(filename: str, data_dir: Path) -> dict[str, object]:
    """Build additive checkpoint metadata for a running long-cost job.

    Metadata fields are omitted when inputs are unavailable. The caller is
    expected to attach this only for non-terminal in-progress polling states.
    """
    checkpoint_filename = create_checkpoint_filename(filename)
    checkpoint_path = data_dir / checkpoint_filename
    final_path = data_dir / filename

    metadata: dict[str, object] = {
        "checkpoint_filename": checkpoint_filename,
        "final_last_modified_if_exists": None,
    }

    final_mtime: float | None = None
    checkpoint_mtime: float | None = None

    try:
        final_mtime = final_path.stat().st_mtime
        metadata["final_last_modified_if_exists"] = _to_epoch_ms(final_mtime)
    except FileNotFoundError:
        pass

    try:
        checkpoint_mtime = checkpoint_path.stat().st_mtime
    except FileNotFoundError:
        return metadata

    metadata["checkpoint_last_modified"] = _to_epoch_ms(checkpoint_mtime)
    metadata["checkpoint_is_newer_than_final"] = (
        final_mtime is None or checkpoint_mtime > final_mtime
    )
    return metadata


def _set_job_runtime_process(
    job_id: str,
    process: "asyncio.subprocess.Process | None",
) -> None:
    """Set or clear the active subprocess handle for *job_id*."""
    runtime = _job_runtime_registry.get(job_id)
    if runtime is not None:
        runtime.process = process


def _clear_job_runtime(job_id: str) -> None:
    """Drop runtime tracking for *job_id* and remove reverse task index."""
    runtime = _job_runtime_registry.pop(job_id, None)
    if runtime is not None:
        _job_id_by_task.pop(runtime.task, None)


# Registry of in-flight and recently-completed jobs.
_job_registry: dict[str, JobStatus] = {}

# Phase 2 runtime index: O(1) lookup of active job task/process by job_id.
_job_runtime_registry: dict[str, JobRuntime] = {}

# Reverse index used by done-callback to clean up job runtime state in O(1).
_job_id_by_task: dict["asyncio.Task[None]", str] = {}

# Anchor set that keeps references to fire-and-forget background Tasks so the
# garbage collector cannot collect them before they complete (CPython allows GC
# of Task objects that have no other referents).
_background_tasks: set["asyncio.Task[None]"] = set()

# Cleanup schedule for the job registry.
_JOB_TTL_S = 900       # evict completed/errored jobs after 15 minutes
_CLEANUP_INTERVAL_S = 60  # run eviction sweep every 60 seconds
_JOB_CANCEL_GRACE_DETAIL = "Cancellation requested by client."
_PROCESS_TERMINATE_GRACE_S = 2.0


def _on_background_task_done(task: "asyncio.Task[None]") -> None:
    """Done-callback: discard the task from the anchor set and log any exception."""
    _background_tasks.discard(task)

    job_id = _job_id_by_task.pop(task, None)
    if job_id is not None:
        _clear_job_runtime(job_id)

    if not task.cancelled():
        exc = task.exception()
        if exc is not None:
            logging.error(
                "Background job task raised an unhandled exception: %s",
                exc,
                exc_info=exc,
            )


async def _cleanup_job_registry_loop() -> None:
    """Periodically evict completed/errored jobs older than _JOB_TTL_S."""
    while True:
        await asyncio.sleep(_CLEANUP_INTERVAL_S)
        now = time.time()
        expired = [
            jid
            for jid, j in list(_job_registry.items())
            if _is_terminal_job_status(j.status) and (now - j.created_at) > _JOB_TTL_S
        ]
        for jid in expired:
            _job_registry.pop(jid, None)
            _clear_job_runtime(jid)
        if expired:
            logging.debug(
                "Evicted %d expired job(s) from registry", len(expired))


def _safe_filename(filename: str) -> bool:
    """Return True if *filename* contains no path-traversal characters."""
    return (
        bool(filename)
        and "/" not in filename
        and "\\" not in filename
        and ".." not in filename
        and "\x00" not in filename
    )


async def run_td_cli(
    action_args: list[str],
    data_dir: Path,
    *,
    timeout_s: float | None = None,
    on_process_started: "Callable[[asyncio.subprocess.Process], None] | None" = None,
    on_process_ended: "Callable[[], None] | None" = None,
) -> int:
    """Invoke td_cli.py as a subprocess and return its exit code.

    *timeout_s* is the hard wall-clock deadline for the subprocess.  When the
    deadline expires the process is killed and ``asyncio.TimeoutError`` is
    re-raised to the caller.  Pass ``None`` (the default) to disable the
    timeout.
    """
    td_cli_path = Path(__file__).parent / "td_cli.py"
    logging.debug("Spawning subprocess: %s %s %s", 
                  sys.executable,
                  td_cli_path, 
                  " ".join(action_args))
    process = await asyncio.create_subprocess_exec(
        sys.executable,
        str(td_cli_path),
        "--datadir", str(data_dir),  # must precede action_args so td_cli.py's
        *action_args,                # top-level parser captures it before subcommand delegation
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    if on_process_started is not None:
        on_process_started(process)
    _t0 = time.monotonic()
    try:
        if timeout_s is not None:
            stdout, stderr = await asyncio.wait_for(
                process.communicate(), timeout=timeout_s
            )
        else:
            stdout, stderr = await process.communicate()
    except asyncio.CancelledError:
        logging.info(
            "Subprocess cancelled; terminating process (args: %s)",
            " ".join(action_args),
        )
        try:
            if process.returncode is None:
                process.terminate()
                try:
                    logging.debug("Waiting up to %.1f s for subprocess to terminate gracefully", _PROCESS_TERMINATE_GRACE_S)
                    await asyncio.wait_for(
                        process.communicate(), timeout=_PROCESS_TERMINATE_GRACE_S
                    )
                except asyncio.TimeoutError:
                    logging.warning("Subprocess did not terminate gracefully; killing process")
                    process.kill()
                    await process.communicate()
        finally:
            raise
    except asyncio.TimeoutError:
        logging.warning(
            "Subprocess timed out after %.1f s (args: %s); killing process",
            timeout_s,
            f"{sys.executable} {td_cli_path} {' '.join(action_args)}",
            )
        process.kill()
        # reap the child to avoid zombie
        await process.communicate()  
        raise
    finally:
        if on_process_ended is not None:
            on_process_ended()
        logging.debug(
            "Subprocess elapsed %.3f s  %s %s %s",
            time.monotonic() - _t0,
            sys.executable,
            td_cli_path,
            " ".join(action_args)
        )
    if stdout:
        logging.info("td_cli stdout: %s", stdout.decode(errors="replace"))
    if stderr:
        logging.warning("td_cli stderr: %s", stderr.decode(errors="replace"))
    return process.returncode  # type: ignore[return-value]


