# Ensure .mjs and other types are served with the right Content-Type on
# minimal container images where the OS mime database may be absent.
mimetypes.add_type("application/javascript", ".js")
mimetypes.add_type("application/javascript", ".mjs")
mimetypes.add_type("application/json", ".json")
mimetypes.add_type("text/css", ".css")
mimetypes.add_type("text/html", ".html")

# Keyed by filename; value is an asyncio.Task running run_td_cli for that file.
# Prevents duplicate concurrent subprocess invocations for the same file.
_active_processes: dict[str, "asyncio.Task[int]"] = {}

# Phase 4 — async job tracking (DD-2 Option B)
_LONG_COST_THRESHOLD_S = 300  # actions with cost > this get 202 + polling


@dataclasses.dataclass
class JobStatus:
    job_id: str
    filename: str
    status: str  # "running" | "done" | "error"
    detail: str = ""


# Registry of in-flight and recently-completed jobs.
_job_registry: dict[str, JobStatus] = {}


def _safe_filename(filename: str) -> bool:
    """Return True if *filename* contains no path-traversal characters."""
    return (
        bool(filename)
        and "/" not in filename
        and "\\" not in filename
        and ".." not in filename
        and "\x00" not in filename
    )


async def run_td_cli(action_args: list[str], data_dir: Path) -> int:
    """Invoke td_cli.py as a subprocess and return its exit code."""
    td_cli_path = Path(__file__).parent / "td_cli.py"  # DD-5
    # logging.debug("Running td_cli with args: %s", " ".join(action_args))
    logging.debug("Spawning subprocess: %s %s", sys.executable, td_cli_path)
    process = await asyncio.create_subprocess_exec(
        sys.executable,
        str(td_cli_path),
        *action_args,
        "--datadir", str(data_dir),  # DD-6
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.PIPE,
    )
    stdout, stderr = await process.communicate()
    if stdout:
        logging.info("td_cli stdout: %s", stdout.decode(errors="replace"))
    if stderr:
        logging.warning("td_cli stderr: %s", stderr.decode(errors="replace"))
    return process.returncode  # type: ignore[return-value]


async def handle_data_api(request: aiohttp.web.Request) -> aiohttp.web.Response:
    """GET /api/data/{filename} — serve or generate a data file."""
    # logging.debug("Received request for %s", request.path)
    filename = request.match_info["filename"]

    # 2a. Reject path traversal.
    if not _safe_filename(filename):
        raise aiohttp.web.HTTPNotFound()

    # 2b. Look up FileAction.
    file_action = get_file_action(filename)
    if file_action is None:
        raise aiohttp.web.HTTPNotFound(reason=f"Unknown filename: {filename}")

    # 2c. Parse Cache-Control request header.
    cc = parse_request_cache_control(request.headers.get("Cache-Control"))
    no_cache = bool(cc.get("no-cache", False))

    # 2d. Resolve full file path.
    data_dir: Path = request.app["td_data_dir"]
    file_path = data_dir / filename

    # 2e/2f. Determine whether to regenerate.
    is_static = file_action.action == "STATIC"
    file_exists = file_path.is_file()

    if is_static:
        # STATIC files are managed externally; never regenerated.
        if not file_exists:
            raise aiohttp.web.HTTPNotFound(
                reason=f"Static file not found: {filename}")
    else:
        needs_regen = (
            not file_exists
            or no_cache
            or not is_file_fresh(file_path, file_action.max_age_s)
        )
        if needs_regen:
            # 2g / 4.1: Run td_cli; deduplicate concurrent requests for the same file.
            # type: ignore[assignment]
            action_args: list[str] = file_action.action

            # Phase 4 (task 4.1): long-cost actions get 202 + polling job API.
            if file_action.action_cost_s > _LONG_COST_THRESHOLD_S:
                # Re-use an existing job for the same filename if already running.
                existing_job = next(
                    (
                        j for j in _job_registry.values()
                        if j.filename == filename and j.status == "running"
                    ),
                    None,
                )
                if existing_job is not None:
                    job_id = existing_job.job_id
                else:
                    job_id = str(uuid.uuid4())
                    job = JobStatus(
                        job_id=job_id, filename=filename, status="running"
                    )
                    _job_registry[job_id] = job

                    async def _run_job(
                        jid: str = job_id,
                        args: list[str] = action_args,
                        ddir: Path = data_dir,
                    ) -> None:
                        exit_code = await run_td_cli(args, ddir)
                        j = _job_registry.get(jid)
                        if j is None:
                            return
                        if exit_code == 0:
                            j.status = "done"
                        else:
                            j.status = "error"
                            j.detail = f"td_cli exit code {exit_code}"

                    asyncio.ensure_future(_run_job())

                body = json.dumps(
                    {
                        "job_id": job_id,
                        "status": "running",
                        "filename": filename,
                    }
                )
                return aiohttp.web.Response(
                    status=202,
                    content_type="application/json",
                    text=body,
                    headers={
                        "Location": f"/api/job/{job_id}",
                        "Access-Control-Allow-Origin": "*",
                    },
                )

            # Short-cost action: run synchronously (original Phase 2 path).
            if filename in _active_processes:
                logging.info("Awaiting existing td_cli task for %s", filename)
                try:
                    await _active_processes[filename]
                except Exception:
                    # Error handling is done by the originating coroutine.
                    pass
                if not file_path.is_file():
                    raise aiohttp.web.HTTPBadGateway(
                        reason=f"td_cli failed for {filename}"
                    )
            else:
                task: asyncio.Task[int] = asyncio.ensure_future(
                    run_td_cli(action_args, data_dir)
                )
                _active_processes[filename] = task
                try:
                    exit_code = await task
                finally:
                    _active_processes.pop(filename, None)
                if exit_code != 0:
                    raise aiohttp.web.HTTPBadGateway(
                        reason=f"td_cli failed for {filename} (exit {exit_code})"
                    )

    # 2h. Read file from data_dir.
    try:
        payload = file_path.read_bytes()
    except OSError as exc:
        logging.error("Failed to read %s: %s", file_path, exc)
        raise aiohttp.web.HTTPInternalServerError()

    # 2i. Send response with cache and CORS headers.
    cache_headers = build_cache_response_headers(file_action.max_age_s)
    suffix = file_path.suffix.lower()
    content_type = "application/json" if suffix == ".json" else "application/octet-stream"

    return aiohttp.web.Response(
        body=payload,
        content_type=content_type,
        headers={
            **cache_headers,
            "Access-Control-Allow-Origin": "*",  # 2.6 CORS
        },
    )


async def handle_job_api(request: aiohttp.web.Request) -> aiohttp.web.Response:
    """GET /api/job/{job_id} — poll the status of a long-running td_cli job."""
    job_id = request.match_info["job_id"]
    job = _job_registry.get(job_id)
    if job is None:
        raise aiohttp.web.HTTPNotFound(reason=f"Unknown job: {job_id}")

    if job.status == "running":
        body = {"status": "running"}
    elif job.status == "done":
        body = {"status": "done", "filename": job.filename}
    else:
        body = {"status": "error", "detail": job.detail}

    return aiohttp.web.Response(
        content_type="application/json",
        text=json.dumps(body),
        headers={"Access-Control-Allow-Origin": "*"},
    )


async def handle_root(request: aiohttp.web.Request) -> aiohttp.web.Response:
    """Redirect / to /tdash.html."""
    raise aiohttp.web.HTTPFound("/tdash.html")


