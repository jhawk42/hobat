def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Start the Thread Network Topology Dashboard web server.",
    )
    parser.add_argument(
        "--verbose", "-v", action="store_true", help="Enable verbose (INFO) logging"
    )
    parser.add_argument(
        "--debug", "-d", action="store_true", help="Enable debug logging"
    )
    parser.add_argument(
        "--host",
        default=os.environ.get("HOST", TD_WEB_HOST_ADDR),
        help=f"Host/address to bind to (default: '{TD_WEB_HOST_ADDR}', env: HOST)",
    )
    parser.add_argument("--datadir", default=None, help=TD_DATA_DIR_ARG_HELP)
    parser.add_argument(
        "--port",
        type=int,
        default=int(os.environ.get("PORT", TD_WEB_HOST_PORT)),
        help=f"Port to listen on (default: {TD_WEB_HOST_PORT}, env: PORT)",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    logging.basicConfig(
        level=logging.INFO, format="[%(asctime)s] %(levelname)s: %(message)s"
    )

    parser = build_parser()
    args = parser.parse_args(argv)

    # Apply verbosity / debug flags
    if args.debug:
        logging.getLogger().setLevel(logging.DEBUG)
    elif args.verbose:
        logging.getLogger().setLevel(logging.INFO)

    static_root = Path(__file__).resolve().parent
    td_data_dir_resolution = resolve_data_dir_with_source(
        datadir_arg=args.datadir)
    td_data_dir = td_data_dir_resolution.path

    logging.info(format_data_dir_log_message(td_data_dir_resolution))

    app = aiohttp.web.Application()
    app["td_data_dir"] = td_data_dir

    # Specific routes are registered before the static catch-all.
    app.router.add_get("/", handle_root)
    app.router.add_get("/api/data/{filename}", handle_data_api)
    app.router.add_get("/api/job/{job_id}", handle_job_api)
    # Serve all static assets (HTML, JS, CSS, …) from the src/ directory.
    app.router.add_static(
        "/", static_root, show_index=False, follow_symlinks=False)

    logging.info("Starting tdash webserver dashboard (aiohttp)...")
    logging.info(
        "Serving at http://%s:%s (/ redirects to /tdash.html)",
        args.host or "localhost",
        args.port,
    )
    logging.info("Static assets root: %s", static_root)
    logging.info("Data root: %s", td_data_dir)

    aiohttp.web.run_app(
        app,
        host=args.host if args.host else None,
        port=args.port,
        access_log=logging.getLogger("aiohttp.access"),
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
