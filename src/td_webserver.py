def get_file_action(filename: str) -> FileAction | None:
    """Case-insensitive lookup in FILE_ACTION_MAP.

    Returns the matching FileAction, or None if the filename is unknown.
    """
    lower = filename.lower()
    for key, action in FILE_ACTION_MAP.items():
        if key.lower() == lower:
            return action
    return None


def is_file_fresh(file_path: Path, max_age_s: int) -> bool:
    """Return True if *file_path* exists and its mtime is within *max_age_s* seconds."""
    try:
        mtime = file_path.stat().st_mtime
    except FileNotFoundError:
        return False
    return (time.time() - mtime) < max_age_s


def parse_request_cache_control(header_value: str | None) -> dict:
    """Parse a Cache-Control request header string into a dict.

    Examples::

        parse_request_cache_control("no-cache")
        # -> {"no-cache": True}

        parse_request_cache_control("max-age=600, no-store")
        # -> {"max-age": 600, "no-store": True}

        parse_request_cache_control(None)
        # -> {}
    """
    if not header_value:
        return {}
    result: dict = {}
    for directive in header_value.split(","):
        directive = directive.strip()
        if "=" in directive:
            name, _, value = directive.partition("=")
            name = name.strip().lower()
            value = value.strip()
            try:
                result[name] = int(value)
            except ValueError:
                result[name] = value
        else:
            result[directive.lower()] = True
    return result


def build_cache_response_headers(max_age_s: int) -> dict[str, str]:
    """Return HTTP response headers for cache control.

    Returns a dict with ``Cache-Control`` and ``Last-Modified`` headers.
    ``Last-Modified`` is set to the current time (UTC) in RFC 2822 format.
    """
    last_modified = email.utils.formatdate(time.time(), usegmt=True)
    return {
        "Cache-Control": f"max-age={max_age_s}",
        "Last-Modified": last_modified,
    }


