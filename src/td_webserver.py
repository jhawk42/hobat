def _non_negative_int(value: str) -> int:
    """argparse type: parse a non-negative integer."""
    try:
        parsed = int(value)
    except ValueError as exc:
        raise argparse.ArgumentTypeError(
            f"invalid int value: {value!r}"
        ) from exc
    if parsed < 0:
        raise argparse.ArgumentTypeError(
            f"value must be >= 0, got {value!r}"
        )
    return parsed


def _resolve_file_cache_max_age(
    args: argparse.Namespace,
    parser: argparse.ArgumentParser,
) -> tuple[int, str]:
    """Resolve cache max-age using CLI > ENV > default precedence."""
    if args.file_cache_max_age is not None:
        return args.file_cache_max_age, "cli"

    env_raw = os.environ.get(TD_FILE_CACHE_MAX_AGE_ENV_NAME)
    if env_raw is not None:
        try:
            parsed = int(env_raw)
        except ValueError:
            parser.error(
                f"Invalid {TD_FILE_CACHE_MAX_AGE_ENV_NAME} value: {env_raw!r}; "
                "expected a non-negative integer."
            )
        if parsed < 0:
            parser.error(
                f"Invalid {TD_FILE_CACHE_MAX_AGE_ENV_NAME} value: {env_raw!r}; "
                "expected a non-negative integer."
            )
        return parsed, "env"

    return TD_DATA_FILE_CACHE_MAX_AGE_DEFAULT, "default"


