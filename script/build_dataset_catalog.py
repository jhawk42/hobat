"""One-shot migration of the browser registry and merge policy into the catalog."""

import json
import subprocess
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from merge_dataset import GROUP_TO_INPUT_FILES, SOURCE_PRECEDENCE  # noqa: E402


def main() -> None:
    path = ROOT / "src/td-dataset-manifest.json"
    manifest = json.loads(path.read_text(encoding="utf-8"))
    fallback = ROOT / "src/js/tdash-catalog-fallback.js"
    if manifest["schemaVersion"] == 2:
        from td_dataset_catalog import load_dataset_catalog
        load_dataset_catalog(path)
        fallback.write_text("// Generated by script/build_dataset_catalog.py.\n"
                            "export const DATASET_CATALOG_FALLBACK = "
                            + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + ";\n",
                            encoding="utf-8")
        print(f"Updated fallback from {len(manifest['datasets'])} catalog datasets")
        return

    registry_url = (ROOT / "src/js/tdash-dataset-registry.js").as_uri()
    result = subprocess.run(
        ["node", "--input-type=module", "-e",
         f'import {{DATASET_REGISTRY, DATASOURCE_REGISTRY, DATASET_CATALOG_FALLBACK}} from "{registry_url}"; '
         'console.log(JSON.stringify({datasets: DATASET_REGISTRY, datasources: DATASOURCE_REGISTRY, vocabulary: DATASET_CATALOG_FALLBACK.vocabulary}));'],
        cwd=ROOT, capture_output=True, text=True, check=True,
    )
    browser = json.loads(result.stdout)
    existing = {entry["value"]: entry for entry in manifest["datasets"]}
    datasets = []
    for entry in browser["datasets"]:
        merged = {**entry, **existing.get(entry["value"], {})}
        merged.pop("mergeInputs", None)
        merged.pop("mergeGroups", None)
        merged["healthEligible"] = merged.get("healthEligible") is True
        datasets.append(merged)

    assigned: set[str] = set()
    groups = {}
    for group, files in GROUP_TO_INPUT_FILES.items():
        if group == "full":
            continue
        legacy = []
        for order, filename in enumerate(files):
            matches = [entry for entry in datasets if entry["source"] == group and filename in entry["files"]]
            if not matches:
                legacy.append({"file": filename, "order": order})
                continue
            chosen = next((entry for entry in matches if entry["files"] == [filename]), matches[0])
            chosen.setdefault("mergeInputs", []).append({"file": filename, "order": order})
            chosen.setdefault("mergeGroups", []).append(group)
            assigned.add(filename)
        groups[group] = {"files": legacy}
    for filename in ("td-mdns-scopes-thread.json", "td-mdns-scopes-matter.json"):
        entry = next(item for item in datasets if item["source"] == "mdns" and filename in item["files"])
        entry.setdefault("mergeInputs", []).append({"file": filename, "enabled": False,
                                                       "disabledReason": "Excluded from the legacy mdns merge group"})
    groups["full"] = {"composedOf": ["otbr-cli", "otbr-restapi", "ha-matter-ws", "mdns"],
                      "excluded": {"system": "Not included in legacy full merge",
                                   "eve": "Not included in legacy full merge"}}
    manifest.update(schemaVersion=2, datasources=browser["datasources"], datasets=datasets,
                    vocabulary=browser["vocabulary"],
                    mergeGroups=groups,
                    authority={"version": "authority-v1", "sourceDefaults": dict(SOURCE_PRECEDENCE),
                               "excludedFromFieldAuthority": ["td-mdns-", "td-static-", ".outcome.", ".partial."]})
    path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    fallback.write_text("// Generated by script/build_dataset_catalog.py.\n"
                        "export const DATASET_CATALOG_FALLBACK = "
                        + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + ";\n",
                        encoding="utf-8")
    print(f"Generated {len(datasets)} datasets, {len(groups)} groups, {len(SOURCE_PRECEDENCE)} ranks")


if __name__ == "__main__":
    main()